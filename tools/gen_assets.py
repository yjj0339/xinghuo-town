def gen_one(item, prompt_json, tries=2):
    rid, (kind, desc, mx) = item
    out = os.path.join(RAW, rid + '.png')
    if os.path.exists(out) and os.path.getsize(out) > 50000:
        return rid, 'skip'
    style = STYLE_CHAR if kind == 'char' else STYLE_ISO
    req = {
        'prompt': desc + '。' + style,
        'negative_prompt': NEG,
        'size': '1280*1280',
        'seed': (abs(hash(rid)) % 2147483000),
    }
    for t in range(tries):
        r = subprocess.run([sys.executable, SKILL, '--request', json.dumps(req, ensure_ascii=False), '--output', out],
                           capture_output=True, text=True, timeout=300, cwd='.')
        if os.path.exists(out) and os.path.getsize(out) > 50000:
            return rid, 'ok'
    return rid, 'FAIL'


def main():
    os.makedirs(RAW, exist_ok=True)
    items = [(k, v) for k, v in MANIFEST.items()]
    q = queue.Queue()
    for it in items:
        q.put(it)
    results = []
    lock = threading.Lock()
    done = [0]

    def worker():
        while True:
            try:
                it = q.get_nowait()
            except queue.Empty:
                return
            rid, st = gen_one(it, None)
            with lock:
                done[0] += 1
                results.append((rid, st))
                print(f'[{done[0]}/{len(items)}] {rid}: {st}', flush=True)

    threads = [threading.Thread(target=worker) for _ in range(3)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    fails = [r for r, s in results if s == 'FAIL']
    print('DONE. fails:', fails if fails else 'none', flush=True)


if __name__ == '__main__':
    main()
